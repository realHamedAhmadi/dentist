<?php

namespace Modules\Auth\Tests\Feature\Services;

use Modules\Auth\DTO\AuthEntryPointsResult;
use Modules\Auth\Services\AuthEntryPointsService;
use Modules\Auth\Services\LoginCaseRegistry;
use Tests\TestCase;

class AuthEntryPointsServiceTest extends TestCase
{
    protected AuthEntryPointsService $service;

    protected function setUp(): void
    {
        parent::setUp(); // TODO: Change the autogenerated stub

        $this->service=new AuthEntryPointsService(app(LoginCaseRegistry::class));
    }

    public function testActiveLoginCase()
    {
        $result=$this->service->get();
        $this->assertInstanceOf(AuthEntryPointsResult::class,$result);
        $this->assertIsArray($result->toArray()['login_cases']);
    }
}
