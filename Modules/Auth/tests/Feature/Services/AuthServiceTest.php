<?php

namespace Modules\Auth\Tests\Feature\Services;

use Illuminate\Foundation\Testing\DatabaseTransactions;
use Modules\Auth\DTO\AuthenticatedResult;
use Modules\Auth\Enums\AuthMethod;
use Modules\Auth\Exceptions\InvalidCredentialsException;
use Modules\Auth\Exceptions\NoLoginCaseFoundException;
use Modules\Auth\Services\AuthService;
use Modules\Auth\Services\LoginCaseRegistry;
use Modules\User\Contracts\Config\VerificationConfigInterface;
use Modules\Verification\Enums\VerificationChannel;
use Modules\Verification\Exceptions\InvalidVerificationCodeException;
use Modules\User\Models\User;
use Modules\Auth\Contracts\TokenProviderInterface;
use Mockery;
use Modules\Verification\Models\VerificationCode;
use Tests\TestCase;

class AuthServiceTest extends TestCase
{
    use DatabaseTransactions;

    protected TokenProviderInterface $tokenProvider;
    protected AuthService $service;
    protected AuthenticatedResult $authenticatedResult;

    protected function setUp(): void
    {
        parent::setUp(); // TODO: Change the autogenerated stub

        $this->tokenProvider = Mockery::mock(TokenProviderInterface::class);
        $this->service = new AuthService(
            app(LoginCaseRegistry::class),
            $this->tokenProvider
        );
        $this->authenticatedResult = new AuthenticatedResult(
            user: User::factory()->make([
                'email' => 'test@example.com',
                'password' => 'secret'
            ]),
            roles: [],
            token: [],
            chooseRole: false
        );
    }

    public function test_login_by_email(): void
    {
        $identifier = 'test@example.com';
        $password = 'secret';
        $user = User::factory()->create([
            'email' => $identifier,
            'password' => $password
        ]);

        $result = $this->service->login($identifier, $password);

        $this->assertInstanceOf(AuthenticatedResult::class, $result);
        $this->assertEquals($user->id, $result->user->id);
    }

    public function test_login_by_phone(): void
    {
        $identifier = '09216549866';
        $password = 'secret';
        $user = User::factory()->create([
            'phone' => $identifier,
            'password' => $password
        ]);

        $result = $this->service->login($identifier, $password);

        $this->assertInstanceOf(AuthenticatedResult::class, $result);
        $this->assertEquals($user->id, $result->user->id);
    }

    public function test_cant_login_with_invalid_password(): void
    {
        $identifier = '09216549866';
        $password = 'secret';
        $user = User::factory()->create([
            'phone' => $identifier,
            'password' => $password
        ]);

        $this->expectException(InvalidCredentialsException::class);
        $result = $this->service->login($identifier, '12sw1w1');
    }

    public function test_cant_login_with_invalid_code(): void
    {
        $identifier = '09216549866';
        $password = 'secret';
        $user = User::factory()->create([
            'phone' => $identifier,
            'password' => $password
        ]);


        $verification = VerificationCode::issue(
            $identifier,
            VerificationChannel::SMS,
            $this->app->make(VerificationConfigInterface::class)
        );

        $this->expectException(InvalidVerificationCodeException::class);
        $result = $this->service->login($identifier, '12sw1w1', ['auth_method' => AuthMethod::CODE->value]);
    }

    public function test_login_throws_exception_when_no_strategy_matches(): void
    {

        $this->expectException(NoLoginCaseFoundException::class);

        $this->service->login('##########**&&&', null);
    }

}
