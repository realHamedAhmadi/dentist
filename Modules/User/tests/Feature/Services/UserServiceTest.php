<?php


namespace Modules\User\Tests\Feature\Services;

use Illuminate\Database\Eloquent\ModelNotFoundException;
use Illuminate\Foundation\Testing\DatabaseTransactions;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Modules\User\Models\Definition\Role;
use Modules\User\Models\Definition\Permission;
use Modules\User\Models\User;
use Modules\User\Services\UserService;
use Tests\TestCase;

class UserServiceTest extends TestCase
{
    use DatabaseTransactions;
    protected UserService $service;


    protected function setUp(): void
    {
        parent::setUp(); // TODO: Change the autogenerated stub
        $this->service=new UserService();
    }

    public function test_create_returns_empty_user_if_phone_or_email_exists()
    {
        // ایجاد یک کاربر اولیه
        $existingUser = User::factory()->create([
            'phone' => '09123456789',
            'email' => 'test@example.com'
        ]);

        // تلاش برای ایجاد کاربر با همان شماره و ایمیل
        $user = $this->service->create([
            'first_name' => 'Ali',
            'last_name' => 'Rezaei',
            'phone' => '09123456789', // شماره موجود
            'email' => 'test@example.com', // ایمیل موجود
            'password' => 'secret'
        ]);

        $this->assertInstanceOf(User::class, $user);
        $this->assertFalse($user->exists); // چون کاربر جدید ایجاد نشده
    }

    public function test_create_creates_new_user_if_not_exists()
    {
        $user = $this->service->create([
            'first_name' => 'Sara',
            'last_name' => 'Ahmadi',
            'phone' => '09987654321',
            'email' => 'sara@example.com',
            'password' => 'secret'
        ]);

        $this->assertInstanceOf(User::class, $user);
        $this->assertTrue($user->exists); // کاربر ایجاد شده
        $this->assertDatabaseHas('users', [
            'id' => $user->id,
            'phone' => '09987654321',
            'email' => 'sara@example.com'
        ]);

        // بررسی اینکه پسورد هش شده ذخیره شده
        $this->assertNotEquals('secret', $user->password);
    }

    /** @test */
    public function it_syncs_roles_including_reserved_roles()
    {
        $user = User::factory()->create();

        $reservedRole = Role::factory()->create(['name' => 'reserved', 'reserved' => true]);
        $normalRole = Role::factory()->create(['name' => 'normal', 'reserved' => false]);

        // افزودن نقش reserved به کاربر
        $user->assignRole($reservedRole);

        // فراخوانی متد Service
        $this->service->syncRoles(['normal'], $user->id);

        $user->refresh();

        $this->assertTrue($user->hasRole('reserved'));
        $this->assertTrue($user->hasRole('normal'));
    }

    /** @test */
    public function it_syncs_multiple_permissions_correctly()
    {
        $user = User::factory()->create();

        $permissions = [
            Permission::factory()->create(['name' => 'edit posts']),
            Permission::factory()->create(['name' => 'delete posts']),
        ];

        $this->service->syncPermissions(['edit posts', 'delete posts'], $user->id);

        $user->refresh();

        foreach ($permissions as $permission) {
            $this->assertTrue($user->hasPermissionTo($permission->name));
        }
    }

    /** @test */
    public function it_throws_exception_if_user_not_found_when_syncing_roles()
    {
        $this->expectException(ModelNotFoundException::class);

        $this->service->syncRoles(['admin'], 9999); // id ناموجود
    }

    /** @test */
    public function it_throws_exception_if_user_not_found_when_syncing_permissions()
    {
        $this->expectException(ModelNotFoundException::class);

        $this->service->syncPermissions(['edit'], 9999); // id ناموجود
    }
}
