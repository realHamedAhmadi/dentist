<?php
namespace Modules\User\Tests\Feature\Services;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Foundation\Testing\DatabaseTransactions;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Modules\User\Http\Resources\Api\V1\Admin\AdminResource;
use Modules\User\Models\Admin;
use Modules\User\Models\Client;
use Modules\User\Models\Staff;
use Modules\User\Models\User;
use Modules\User\Services\AdminService;
use Modules\User\Services\StaffService;
use Modules\User\Models\Definition\Role;
use Modules\User\Tests\Feature\Services\MemberBaseServiceTest;

class AdminServiceTest extends MemberBaseServiceTest
{
    use DatabaseTransactions;
    protected string $serviceClass=AdminService::class;
    protected string $roleName=Role::ROLE_ADMIN;
    protected string $modelClass=Admin::class;

    protected string $userHasRoleTbl;

    protected function setUp(): void
    {
        parent::setUp(); // TODO: Change the autogenerated stub
        $this->userHasRoleTbl=config('permission.table_names.model_has_roles');

    }

    protected function createRecordWithUser(array $attributes = []): Model
    {
        $user = User::factory()->create();
        return $this->modelClass::factory()->create([
            'user_id' => $user->id,
        ]);
    }


    protected function callProtected(object $object, string $method, array $params = [])
    {
        $reflection = new \ReflectionClass($object);
        $method = $reflection->getMethod($method);
        $method->setAccessible(true);
        return $method->invokeArgs($object, $params);
    }

    /** @test */
    public function it_syncs_roles_on_create()
    {
        $admin = $this->createRecordWithUser();
        $role1 = Role::factory()->create(['name'=>'role1']);
        $role2 = Role::factory()->create(['name'=>'role2']);

        $data = [
            'roles' => [$role1->name,$role2->name],
            'first_name'=>''
        ];

        $this->callProtected(app($this->serviceClass), 'created', [$admin, $data]);

        $this->assertDatabaseHas($this->userHasRoleTbl, [
            'user_id' => $admin->user_id,
            'role_id' => $role1->id,
        ]);
    }

    /** @test */
    public function it_create_client_on_create()
    {
        $admin = $this->createRecordWithUser();

        $data=[
            'first_name'=>$admin->first_name,
        ];
        $this->callProtected(app($this->serviceClass), 'created', [$admin,$data ]);

        $this->assertDatabaseHas(Client::table(), [
            'user_id' => $admin->user_id,
        ]);
    }

    /** @test */
    public function it_syncs_roles_on_update()
    {
        $admin = $this->createRecordWithUser();

        $user=$admin->user;
        $role1 = Role::factory()->create(['name'=>'role1']);
        $role2 = Role::factory()->create(['name'=>'role2']);

        $user->assignRole($role1->name);

        $this->assertDatabaseHas($this->userHasRoleTbl, [
            'user_id'=>$admin->user_id,
            'role_id'=>$role1->id
        ]);

        $data = [
            'roles' => [$role2->name]
        ];

        $this->callProtected(app($this->serviceClass), 'updated', [$admin, $data]);

        $this->assertDatabaseHas($this->userHasRoleTbl, [
            'user_id' => $user->id,
            'role_id' => $role2->id,
        ]);

        $this->assertDatabaseMissing($this->userHasRoleTbl,[
            'user_id' => $user->id,
            'role_id' => $role1->id,
        ]);
    }

    /** @test */
    public function it_detaches_roles_when_deleting_admin()
    {
        $admin = $this->createRecordWithUser();
        $role = Role::factory()->create(['name'=>'role']);

        $admin->user->assignRole($role->name);
        $this->assertDatabaseHas($this->userHasRoleTbl, [
            'user_id'=>$admin->user_id,
            'role_id'=>$role->id
        ]);

        $this->callProtected(app($this->serviceClass), 'deleting', [$admin]);

        $this->assertDatabaseMissing($this->userHasRoleTbl, [
            'user_id'=>$admin->user_id,
            'role_id'=>$role->id
        ]);
    }
}
